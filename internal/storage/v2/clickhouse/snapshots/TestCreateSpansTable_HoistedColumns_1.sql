CREATE TABLE
    IF NOT EXISTS spans (
        id String,
        trace_id String,
        trace_state String,
        parent_span_id String,
        name String,
        kind String,
        start_time DateTime64 (9),
        status_code String,
        status_message String,
        duration Int64,
        bool_attributes Nested (key String, value Bool),
        double_attributes Nested (key String, value Float64),
        int_attributes Nested (key String, value Int64),
        str_attributes Nested (key String, value String),
        complex_attributes Nested (key String, value String),
        events Nested (
            name String,
            timestamp DateTime64 (9),
            bool_attributes Nested (key String, value Bool),
            double_attributes Nested (key String, value Float64),
            int_attributes Nested (key String, value Int64),
            str_attributes Nested (key String, value String),
            complex_attributes Nested (key String, value String)
        ),
        links Nested (
            trace_id String,
            span_id String,
            trace_state String,
            bool_attributes Nested (key String, value Bool),
            double_attributes Nested (key String, value Float64),
            int_attributes Nested (key String, value Int64),
            str_attributes Nested (key String, value String),
            complex_attributes Nested (key String, value String)
        ),
        service_name String,
        resource_bool_attributes Nested (key String, value Bool),
        resource_double_attributes Nested (key String, value Float64),
        resource_int_attributes Nested (key String, value Int64),
        resource_str_attributes Nested (key String, value String),
        resource_complex_attributes Nested (key String, value String),
        scope_name String,
        scope_version String,
        scope_bool_attributes Nested (key String, value Bool),
        scope_double_attributes Nested (key String, value Float64),
        scope_int_attributes Nested (key String, value Int64),
        scope_str_attributes Nested (key String, value String),
        scope_complex_attributes Nested (key String, value String),
        `span_str` Nullable(String) MATERIALIZED if(has(str_attributes.key, 'gen_ai.request.model'), str_attributes.value[indexOf(str_attributes.key, 'gen_ai.request.model')], NULL) CODEC(ZSTD(1)),
        `span_int` Nullable(Int64) MATERIALIZED if(has(int_attributes.key, 'gen_ai.usage.input_tokens'), int_attributes.value[indexOf(int_attributes.key, 'gen_ai.usage.input_tokens')], NULL) CODEC(ZSTD(1)),
        `span_double` Nullable(Float64) MATERIALIZED if(has(double_attributes.key, 'ratio'), double_attributes.value[indexOf(double_attributes.key, 'ratio')], NULL) CODEC(ZSTD(1)),
        `span_bool` Nullable(Bool) MATERIALIZED if(has(bool_attributes.key, 'cached'), bool_attributes.value[indexOf(bool_attributes.key, 'cached')], NULL) CODEC(ZSTD(1)),
        `resource_str` Nullable(String) MATERIALIZED if(has(resource_str_attributes.key, 'gen_ai.request.model'), resource_str_attributes.value[indexOf(resource_str_attributes.key, 'gen_ai.request.model')], NULL) CODEC(ZSTD(1)),
        `resource_int` Nullable(Int64) MATERIALIZED if(has(resource_int_attributes.key, 'shard'), resource_int_attributes.value[indexOf(resource_int_attributes.key, 'shard')], NULL) CODEC(ZSTD(3)),
        `index` Nullable(String) MATERIALIZED if(has(resource_str_attributes.key, 'it\'s a \\key'), resource_str_attributes.value[indexOf(resource_str_attributes.key, 'it\'s a \\key')], NULL) CODEC(ZSTD(1)),
        INDEX idx_trace_id trace_id TYPE bloom_filter GRANULARITY 1,
        INDEX idx_duration duration TYPE minmax GRANULARITY 1
    ) ENGINE = MergeTree
PARTITION BY toDate(start_time)
ORDER BY (service_name, name, toDateTime(start_time))
